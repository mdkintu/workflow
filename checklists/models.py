"""ChecklistTemplate/Item/RecurrenceRule (not synced) and
ChecklistRun/RunItem/RunItemTick (synced). See docs/04-design.md §1.2.
Runs are generated by checklists/generator.py; their status changes only
through checklists/runs.py.
"""

from __future__ import annotations

